"""Migrations upgrade, downgrade and upgrade again, and match the models."""

from alembic import command
from sqlalchemy import create_engine, inspect

from app.db.base import Base
from tests.database import alembic_config, throwaway_database


def _tables(url: str) -> set[str]:
    engine = create_engine(url)
    try:
        return set(inspect(engine).get_table_names())
    finally:
        engine.dispose()


def test_upgrade_downgrade_round_trip() -> None:
    with throwaway_database() as url:
        cfg = alembic_config(url)
        command.upgrade(cfg, "head")
        assert set(Base.metadata.tables) <= _tables(url)

        command.downgrade(cfg, "base")
        assert _tables(url) == {"alembic_version"}

        command.upgrade(cfg, "head")
        assert set(Base.metadata.tables) <= _tables(url)


def test_revoked_sessions_migration_round_trips() -> None:
    with throwaway_database() as url:
        cfg = alembic_config(url)
        command.upgrade(cfg, "0008_revoked_sessions")
        assert "revoked_sessions" in _tables(url)
        command.downgrade(cfg, "0007_ai_runs")
        assert "revoked_sessions" not in _tables(url)
        command.upgrade(cfg, "0008_revoked_sessions")
        assert "revoked_sessions" in _tables(url)


def test_models_match_migrations(database_url: str) -> None:
    # Raises AutogenerateDiffsDetected if the models and the migrated schema differ.
    command.check(alembic_config(database_url))
